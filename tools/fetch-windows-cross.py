#!/usr/bin/env python3
"""Fetch the pinned Linux-to-Windows cross toolchain into vendor/windows.

Downloads and verifies tools/windows-cross.lock.json: llvm-mingw, the MSYS2
UCRT64 libraries Jotta Text links and bundles, and NSIS (run under Wine). Then
unpacks them and writes dist/windows-cross.ini for Meson. With --offline only
previously downloaded archives are used.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile
import urllib.request
import zipfile

ROOT=Path(__file__).resolve().parent.parent
LOCK_FILE=ROOT/'tools/windows-cross.lock.json'
BASE=ROOT/'vendor/windows'
DOWNLOADS=BASE/'downloads'
STAMP=BASE/'.lock-sha256'

def fetch(archive,offline):
    path=DOWNLOADS/archive['url'].rsplit('/',1)[1]
    if path.is_file() and hashlib.sha256(path.read_bytes()).hexdigest()==archive['sha256']:return path
    if offline:raise SystemExit(f'Missing or changed download {path.name}; run once without --offline.')
    print(f'Downloading {path.name}')
    with urllib.request.urlopen(archive['url'],timeout=120) as response:data=response.read()
    if hashlib.sha256(data).hexdigest()!=archive['sha256']:raise SystemExit(f'Checksum mismatch for {path.name}')
    DOWNLOADS.mkdir(parents=True,exist_ok=True)
    path.write_bytes(data)
    return path

def extract_tar(tar,destination):
    # The data filter refuses absolute paths and links leaving the destination.
    if hasattr(tarfile,'data_filter'):tar.extractall(destination,filter='data')
    else:tar.extractall(destination)

def unpack_single_folder(extract,archive,destination):
    """Unpack an archive whose content sits in one top-level folder to destination."""
    with tempfile.TemporaryDirectory(dir=BASE) as temp:
        extract(archive,Path(temp))
        (top,)=Path(temp).iterdir()
        shutil.rmtree(destination,ignore_errors=True)
        top.rename(destination)

def zstd_bytes(path):
    try:
        from compression import zstd  # Python 3.14+
        return zstd.decompress(path.read_bytes())
    except ImportError:
        return subprocess.run(['zstd','-dc',str(path)],capture_output=True,check=True).stdout

def write_meson_cross_file():
    tools=BASE/'toolchain/bin';sysroot=BASE/'sysroot';prefix=sysroot/'ucrt64'
    text=f"""# Generated by tools/fetch-windows-cross.py.
[binaries]
c = '{tools}/x86_64-w64-mingw32-clang'
ar = '{tools}/x86_64-w64-mingw32-ar'
strip = '{tools}/x86_64-w64-mingw32-strip'
windres = '{tools}/x86_64-w64-mingw32-windres'
pkg-config = 'pkg-config'
[host_machine]
system = 'windows'
cpu_family = 'x86_64'
cpu = 'x86_64'
endian = 'little'
[properties]
needs_exe_wrapper = true
sys_root = '{sysroot}'
pkg_config_libdir = ['{prefix}/lib/pkgconfig', '{prefix}/share/pkgconfig']
[built-in options]
c_args = ['-idirafter', '{prefix}/include']
c_link_args = ['-L{prefix}/lib']
"""
    (ROOT/'dist').mkdir(exist_ok=True)
    (ROOT/'dist/windows-cross.ini').write_text(text)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--offline',action='store_true')
    args,_=parser.parse_known_args()
    lock=json.loads(LOCK_FILE.read_text())
    BASE.mkdir(parents=True,exist_ok=True)
    stamp=hashlib.sha256(LOCK_FILE.read_bytes()).hexdigest()
    if STAMP.is_file() and STAMP.read_text()==stamp and all((BASE/name).is_dir() for name in ('toolchain','sysroot','nsis')):
        write_meson_cross_file()
        print('Windows cross toolchain ready')
        return
    toolchain=fetch(lock['toolchain'],args.offline)
    nsis=fetch(lock['nsis'],args.offline)
    packages=[fetch(package,args.offline) for package in lock['packages']]
    def untar_xz(path,destination):
        with tarfile.open(path,'r:xz') as tar:extract_tar(tar,destination)
    def unzip(path,destination):
        with zipfile.ZipFile(path) as zipped:zipped.extractall(destination)
    unpack_single_folder(untar_xz,toolchain,BASE/'toolchain')
    unpack_single_folder(unzip,nsis,BASE/'nsis')
    sysroot=BASE/'sysroot'
    shutil.rmtree(sysroot,ignore_errors=True);sysroot.mkdir()
    for package in packages:
        with tarfile.open(fileobj=io.BytesIO(zstd_bytes(package))) as tar:
            members=[member for member in tar.getmembers() if not member.name.startswith('.')]
            tar.extractall(sysroot,members=members,**({'filter':'data'} if hasattr(tarfile,'data_filter') else {}))
    STAMP.write_text(stamp)
    write_meson_cross_file()
    print(f'Windows cross toolchain ready ({len(packages)} UCRT64 packages)')

if __name__=='__main__':
    main()
